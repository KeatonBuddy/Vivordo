  /// Capacity's sleep need, as Home and My Day use it (null while it's the
  /// 8 h placeholder).
  double? _sleepNeed;

  Future<void> _loadSleepNeed() async {
    final uid = FirebaseAuth.instance.currentUser?.uid;
    if (uid == null) return;
    final today = DateUtils.dateOnly(DateTime.now());
    try {
      final scores = await FirebaseFirestore.instance
          .collection('users')
          .doc(uid)
          .collection('scores_daily')
          .where(
            FieldPath.documentId,
            isGreaterThanOrEqualTo: localDayKey(
              today.subtract(const Duration(days: 13)),
            ),
          )
          .where(FieldPath.documentId, isLessThanOrEqualTo: localDayKey(today))
          .get();
      final need = latestSleepNeed({
        for (final doc in scores.docs) doc.id: doc.data(),
      });
      if (mounted && need != _sleepNeed) setState(() => _sleepNeed = need);
    } catch (error) {
      debugPrint('Sleep need failed to load: $error');
    }
  }

  int get _rangeDays => switch (_rangeIndex) {
    0 => 1,
    1 => 7,
    _ => 30,
  };
  String _previousName() => switch (_rangeIndex) {
    0 => 'the night before',
    1 => 'the week before',
    _ => 'the month before',
  };

  String get _rangeName => switch (_rangeIndex) {
    0 => 'Daily',
    1 => 'Weekly',
    _ => 'Monthly',
  };

  Future<void> _refreshSleepIfMissing() async {
    final uid = FirebaseAuth.instance.currentUser?.uid;
    if (uid == null || _refreshingSleep) return;

    final firestore = FirebaseFirestore.instance;
    final userReference = firestore.collection('users').doc(uid);
    final todayReference = userReference
        .collection('metrics_daily')
        .doc(localDayKey(DateTime.now()));

    try {
      _refreshingSleep = true;
      final today = await todayReference.get(
        const GetOptions(source: Source.server),
      );
      if (hasRecordedSleep(today.data())) {
        if (mounted) setState(() => _lastRefreshAt = DateTime.now());
        return;
      }

      final user = await userReference.get();
      // Include yesterday to cover sleep spanning midnight.
      await refreshConnectedSleepSources(
        user.data() ?? {},
        whoop: () => WhoopService.instance.sync(daysBack: 2, force: true),
        fitbit: () => FitbitService.instance.sync(daysBack: 2),
        appleHealth: () => HealthService().syncMetric('sleep', daysBack: 2),
      );

      final refreshed = await todayReference.get(
        const GetOptions(source: Source.server),
      );
      final updated = hasRecordedSleep(refreshed.data());
      if (!mounted) return;
      setState(() => _lastRefreshAt = DateTime.now());
      showToast(
        context,
        updated ? 'Sleep updated.' : 'No sleep data available.',
        kind: updated ? ToastKind.success : ToastKind.info,
      );
    } catch (error) {
      debugPrint('[SleepDetailScreen] Sleep refresh failed: $error');
      if (mounted) {
        showToast(
          context,
          "Couldn't refresh sleep. Try again.",
          kind: ToastKind.error,
        );
      }
    } finally {
      _refreshingSleep = false;
    }
  }

  Stream<DocumentSnapshot<Map<String, dynamic>>>? _userStream() {
    final uid = FirebaseAuth.instance.currentUser?.uid;
    return uid == null
        ? null
        : FirebaseFirestore.instance.collection('users').doc(uid).snapshots();
  }

  Stream<QuerySnapshot<Map<String, dynamic>>> _sleepStream() {
    final uid = FirebaseAuth.instance.currentUser?.uid;
    if (uid == null) return const Stream.empty();
    final today = DateUtils.dateOnly(DateTime.now());
    final oldest = today.subtract(const Duration(days: 59));
    return FirebaseFirestore.instance
        .collection('users')
        .doc(uid)
        .collection('metrics_daily')
        .where(
          FieldPath.documentId,
          isGreaterThanOrEqualTo: localDayKey(oldest),
        )
        .where(FieldPath.documentId, isLessThanOrEqualTo: localDayKey(today))
        .orderBy(FieldPath.documentId)
        .snapshots();
  }

