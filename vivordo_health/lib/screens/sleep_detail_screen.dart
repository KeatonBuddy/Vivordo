bool hasRecordedSleep(Map<String, dynamic>? dailyMetrics) {
  final sleep = dailyMetrics?['sleep'];
  if (sleep is! Map) return false;
  final hours = (sleep['avg'] as num?)?.toDouble();
  return hours != null && hours > 0;
}

bool hasConnectedWhoop(Map<String, dynamic>? userData) =>
    userData?['whoopConnected'] == true;

/// Refresh sequentially so the existing wearable/Apple fallback policy applies.
/// A failed provider must not prevent the other connected providers from syncing.
Future<void> refreshConnectedSleepSources(
  Map<String, dynamic> userData, {
  required Future<void> Function() whoop,
  required Future<void> Function() fitbit,
  required Future<void> Function() appleHealth,
}) async {
  final consent = userData['healthKitConsent'];
  final sources = <Future<void> Function()>[
    if (userData['whoopConnected'] == true) whoop,
    if (userData['fitbitConnected'] == true) fitbit,
    if (consent is Map && consent['sleep'] == true) appleHealth,
  ];
  for (final sync in sources) {
    try {
      await sync();
    } catch (error) {
      debugPrint('[SleepDetailScreen] Sleep source refresh failed: $error');
    }
  }
}

/// The minutes after midnight of [day]'s first event in an effort_inputs
/// document, or null when it has none that day.
int? firstEventMinutes(String day, Map<String, dynamic> data) {
  final date = DateTime.tryParse(day);
  final events = data['events'];
  if (date == null || events is! List) return null;
  final starts = [
    for (final event in events)
      if (event is Map && event['start'] is Timestamp)
        (event['start'] as Timestamp).toDate().toLocal(),
  ].where((start) => DateUtils.isSameDay(start, date));
  return starts.isEmpty
      ? null
      : starts.map((start) => start.hour * 60 + start.minute).reduce(math.min);
}

bool includesWhoopSleepSource(Iterable<String?> sources) =>
    sources.any((source) => source?.toLowerCase() == 'whoop');

String sleepInsightInfoText({required bool hasWhoopSleepData}) =>
    hasWhoopSleepData
    ? 'This insight was generated by Vivordo using sleep data imported from WHOOP. WHOOP provides the underlying sleep measurements; the interpretation shown here is created by Vivordo.'
    : 'This insight was generated by Vivordo using your sleep data. The interpretation shown here is created by Vivordo.';

