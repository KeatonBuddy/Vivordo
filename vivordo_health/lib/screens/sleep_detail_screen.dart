  Widget _content(QuerySnapshot<Map<String, dynamic>>? snapshot) {
    final byDay = <String, _SleepValue>{};
    for (final doc in snapshot?.docs ?? const []) {
      final raw = doc.data()['sleep'] as Map?;
      if (raw == null) continue;
      final hours = (raw['avg'] as num?)?.toDouble();
      if (hours == null || hours <= 0) continue;
      byDay[doc.id] = _SleepValue(
        hours: hours,
        bedtime: (raw['bedtime'] as Timestamp?)?.toDate().toLocal(),
        wakeTime: (raw['wakeTime'] as Timestamp?)?.toDate().toLocal(),
        stages: _stageValues(raw['stages'] as Map?),
        source: raw['source'] as String?,
        inBed: raw['measure'] == 'inBed',
      );
    }
    final today = DateUtils.dateOnly(DateTime.now());
    final days = List.generate(_rangeDays, (index) {
      final date = today.subtract(Duration(days: _rangeDays - index - 1));
      return _SleepDay(date, byDay[localDayKey(date)]);
    });
    final previousCutoff = today.subtract(Duration(days: _rangeDays));
    final previous = (snapshot?.docs ?? const [])
        .where((doc) {
          final date = DateTime.tryParse(doc.id);
          return date != null &&
              date.isBefore(previousCutoff) &&
              !date.isBefore(
                previousCutoff.subtract(Duration(days: _rangeDays)),
              );
        })
        .map(
          (doc) => ((doc.data()['sleep'] as Map?)?['avg'] as num?)?.toDouble(),
        )
        .whereType<double>()
        .where((hours) => hours > 0)
        .toList();
    final recorded = days.where((day) => day.value != null).toList();
    final total = recorded.fold<double>(
      0,
      (total, day) => total + day.value!.hours,
    );
    final average = recorded.isEmpty ? 0.0 : total / recorded.length;
    final previousAverage = previous.isEmpty
        ? null
        : previous.reduce((a, b) => a + b) / previous.length;
    // Nothing to compare until this period has a night.
    final changeMinutes = previousAverage == null || recorded.isEmpty
        ? null
        : ((average - previousAverage) * 60).round();
    final latest = recorded.isEmpty ? null : recorded.last.value;
    final need = _sleepNeed;
    final planningAdvice =
        _rangeIndex == 0 &&
            latest != null &&
            need != null &&
            latest.hours < need - .75
        ? 'That is less sleep than you need. Consider keeping your plan flexible and leaving room for a break, especially if you feel tired.'
        : 'Consider how rested you feel alongside this measurement when planning your day. Want help leaving room for rest?';
    final hasWhoopSleepData = includesWhoopSleepSource(
      recorded.map((day) => day.value?.source),
    );
    final averageStages = _averageStages(recorded);
    final nights = {
      for (final MapEntry(:key, :value) in byDay.entries)
        ?DateTime.tryParse(key): SleepNight(
          value.hours,
          value.bedtime,
          value.wakeTime,
          value.inBed,
        ),
    };
    final patterns = sleepPatterns(
      nights: nights,
      today: DateTime.now(),
      need: need,
      tags: _tags,
      ratings: {
        for (final doc in snapshot?.docs ?? const [])
          if ((doc.data()['morning_check_in'] as Map?)?['sleep']
              case final num rating)
            ?DateTime.tryParse(doc.id): rating.toDouble(),
      },
      firstEvents: _firstEvents,
    );
    final sleepingHeartRate = _rangeIndex == 0 && latest != null
        ? _heartRateDuringSleep(snapshot, latest)
        : const <HeartRateHistoryReading>[];

    final insight = ScreenInsight(
      'sleep',
      '$_rangeName sleep',
      // What the card can't say: against the need and the usual bedtime.
      // (This used to be a "Vivordo Insight" section at the foot of the
      // page, with the bar saying something more general.)
      recorded.isEmpty
          ? 'No sleep data is available for this period. Refresh your connected source before drawing conclusions about recovery.'
          : sleepInsight(
              nights: nights,
              today: DateTime.now(),
              rangeDays: _rangeDays,
              need: _sleepNeed,
            ).text,
      // For Vivordo AI only: the number the card already shows, and the
      // planning note.
      context: recorded.isEmpty
          ? null
          : 'Averaged ${hoursMinutes(average)} a night across '
                '${recorded.length} recorded '
                '${recorded.length == 1 ? 'night' : 'nights'} in this view. '
                '$planningAdvice',
      source: sleepInsightInfoText(hasWhoopSleepData: hasWhoopSleepData),
    );
    final needBar = sleepNeedBar(
      hours: average,
      need: _sleepNeed,
      nights: byDay.length,
    );

    return RefreshIndicator(
      color: _purple,
      onRefresh: _refreshSleepIfMissing,
      child: SingleChildScrollView(
        physics: const AlwaysScrollableScrollPhysics(
          parent: BouncingScrollPhysics(),
        ),
        padding: const EdgeInsets.fromLTRB(20, 4, 20, 40),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            _lastUpdatedStatus(
              hasWhoopSleepData: hasWhoopSleepData,
              synced: recorded.isNotEmpty,
            ),
            const SizedBox(height: 18),
            _rangeSelector(),
            const SizedBox(height: 18),
            // W and M use the same card as 6M and Y, so the bars morph.
            if (_rangeIndex == 0) ...[
              _summaryCard(average, total, changeMinutes, latest, needBar),
              const SizedBox(height: 24),
              const Text(
                'Heart rate during sleep',
                style: TextStyle(fontSize: 22, fontWeight: FontWeight.w900),
              ),
              const SizedBox(height: 10),
              _sleepHeartRateChart(sleepingHeartRate, latest),
            ] else
              MetricChartCard(
                label: 'Average night',
                number: _duration(average),
                unit: '',
                range: dayRangeText(days.first.date),
                note: changeMinutes == null ? null : _changeText(changeMinutes),
                chart: _sleepChart(days),
                caption:
                    'Each bar is a night.'
                    '${_sleepNeed == null ? '' : ' The dashed line is your sleep need.'}'
                    ' The solid bar is your longest night.',
                footer: _needAndTimes(needBar, latest),
              ),
            if (_rangeIndex != 0) ...[
              const SizedBox(height: 26),
              const Text(
                'By night',
                style: TextStyle(fontSize: 22, fontWeight: FontWeight.w900),
              ),
              const SizedBox(height: 10),
              MetricDayBreakdown(
                month: _rangeIndex == 2,
                color: HistoryMetric.sleep.color,
                mark: _sleepNeed,
                // Nights differ by an hour or so: from 0 they'd all look
                // alike, so the lines and shades start under the shortest.
                scaleMin:
                    [
                      for (final day in days) ?day.value?.hours,
                    ].fold<double>(24, math.min).clamp(1.0, 24.0) -
                    1,
                compact: HistoryMetric.sleep.compact,
                selected: _day,
                onSelected: _pick,
                days: [
                  for (final day in days)
                    (
                      date: day.date,
                      value: day.value?.hours ?? 0,
                      text: day.value == null
                          ? 'No sleep'
                          : hoursMinutes(day.value!.hours),
                      note: _needNote(day.value?.hours),
                      met:
                          _sleepNeed != null &&
                          day.value != null &&
                          (day.value!.hours - _sleepNeed!) * 60 > -15,
                      hours: null,
                    ),
                ],
              ),
            ],
            const SizedBox(height: 24),
            Text(
              _rangeIndex == 0
                  ? "Last night's sleep stages"
                  : 'Average sleep stages',
              style: TextStyle(fontSize: 22, fontWeight: FontWeight.w900),
            ),
            const SizedBox(height: 10),
            _stagesCard(
              averageStages,
              average,
              hasWhoopSleepData: hasWhoopSleepData,
              inBed: _rangeIndex == 0 && latest?.inBed == true,
            ),
            const SizedBox(height: 24),
            SleepPatternsSection(patterns: patterns, onAction: _patternAction),
          ],
        ),
      ),
    ).withScreenInsight(insight);
  }

  /// "Updated" only once something has synced; never the current time
  /// for a screen with no sleep.
  Widget _lastUpdatedStatus({
    required bool hasWhoopSleepData,
    required bool synced,
  }) {
    final user = FirebaseAuth.instance.currentUser;
    return Center(
      child: StreamBuilder<DocumentSnapshot<Map<String, dynamic>>>(
        stream: _user,
        builder: (context, snapshot) {
          final whoopConnected = hasConnectedWhoop(snapshot.data?.data());
          return Wrap(
            alignment: WrapAlignment.center,
            crossAxisAlignment: WrapCrossAlignment.center,
            spacing: 6,
            runSpacing: 2,
            children: [
              Text(
                synced
                    ? 'Updated ${DateFormat('h:mm a').format(_lastRefreshAt ?? DateTime.now())}'
                    : 'Not synced yet',
                style: TextStyle(color: context.vivordoColors.textSecondary),
              ),
              if (whoopConnected && hasWhoopSleepData) ...[
                Text(
                  '· Data includes',
                  style: TextStyle(color: context.vivordoColors.textSecondary),
                ),
                const WhoopSourceBadge(compact: true),
              ],
            ],
          );
        },
      ),
    );
  }

  /// The day picked in the chart or in "By day" (an index into the range's
  /// days); both show the same one.
  int? _day;

  void _pick(int? day) => setState(() => _day = day);

  /// A night against the need: within 15 minutes is at it.
  String _needNote(double? hours) {
    final need = _sleepNeed;
    if (hours == null || need == null) return '';
    final gap = ((hours - need) * 60).round();
    if (gap.abs() < 15) return 'About your need';
    return '${hoursMinutes(gap.abs() / 60)} ${gap < 0 ? 'short' : 'over'}';
  }

  Widget _rangeSelector() => AppSegmented<int>(
    segments: const {0: 'D', 1: 'W', 2: 'M', 3: '6M', 4: 'Y'},
    value: _rangeIndex,
    onChanged: (index) => setState(() {
      _rangeIndex = index;
      _day = null;
    }),
  );

